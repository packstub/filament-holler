    const MUTE = 'filament-holler::mute';

    const UNMUTE = 'filament-holler::unmute';

    const CAMERA_ON = 'filament-holler::camera-on';

    const CAMERA_OFF = 'filament-holler::camera-off';

    const SHARE_SCREEN = 'filament-holler::share-screen';

    const OPEN_WINDOW = 'filament-holler::open-window';

    const MUTED = 'filament-holler::muted';

